-- Run this once in the Supabase SQL Editor.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  supplier_code text not null,
  supplier_name text not null,
  factories jsonb not null check (jsonb_typeof(factories) = 'array' and jsonb_array_length(factories) > 0),
  full_name text not null check (char_length(full_name) between 2 and 120),
  email text not null check (char_length(email) <= 254),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.registrations enable row level security;

-- Keep the browser role insert-only. Neither public role can read registrations.
revoke all on table public.registrations from anon, authenticated;
grant insert on table public.registrations to anon;
revoke all on sequence public.registrations_id_seq from anon, authenticated;
grant usage on sequence public.registrations_id_seq to anon;

-- Anonymous visitors can submit registrations but cannot read them back.
do $$
begin
  create policy "Public can submit registrations"
  on public.registrations
  for insert
  to anon
  with check (
    status = 'pending'
    and jsonb_typeof(factories) = 'array'
    and jsonb_array_length(factories) > 0
  );
exception
  when duplicate_object then null;
end
$$;

-- Prevent accidental duplicate submissions for the same supplier and email.
create unique index if not exists registrations_supplier_email_key
on public.registrations (supplier_code, lower(email));
